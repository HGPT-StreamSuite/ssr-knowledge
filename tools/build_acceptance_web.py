"""Generate the static, synthetic-only schema bundle; no DB/network/dependencies."""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "web" / "acceptance" / "dist" / "data.js"
FIXTURES = ["prebuild-source.json", "gap-export.json", "gap-records.json", "research-packet.json", "tool-config.json"]
LABELS = {
    "candidate.schema.json": "待審候選 · Candidate",
    "gap-export.schema.json": "知識缺口 · Gap export",
    "prebuild-source.schema.json": "預建來源 · Prebuild source",
    "published-bundle.schema.json": "已發布包的結構 · Published bundle",
    "record.schema.json": "單筆知識 · Record",
    "research-packet.schema.json": "離線研究包 · Research packet",
    "supplement-records.schema.json": "補充記錄 · Supplement records",
    "tool-config.schema.json": "斷線工具設定 · Tool config",
}


def read(path: Path):
    return json.loads(path.read_text(encoding="utf-8"))


def bundle() -> dict:
    schemas = {path.name: read(path) for path in sorted((ROOT / "contracts").glob("*.schema.json"))}
    if set(schemas) != set(LABELS):
        raise ValueError("Contract inventory changed; review labels, numeric semantics and acceptance before rebuilding.")
    # Current schemas have no numeric fields. Do not silently claim Python/JS numeric parity.
    def reject_numeric_fields(value):
        if isinstance(value, dict):
            kind = value.get("type")
            if kind in ("integer", "number") or isinstance(kind, list) and set(kind) & {"integer", "number"}:
                raise ValueError("Numeric schema fields require explicit Python/JavaScript parser parity work.")
            for item in value.values():
                reject_numeric_fields(item)
        elif isinstance(value, list):
            for item in value:
                reject_numeric_fields(item)
    reject_numeric_fields(schemas)
    fixtures = {name: read(ROOT / "fixtures" / name) for name in FIXTURES}
    records = fixtures["prebuild-source.json"]["records"]
    candidate = {"candidate_id": "fixture-web-candidate", "origin": "prebuild", "status": "pending_review",
                 "created_at": "2026-10-17T00:00:00Z", "source_reference": "fixture-prebuild-001",
                 "research_id": None, "records": records, "review": None}
    canonical = json.dumps(records, ensure_ascii=False, sort_keys=True, separators=(",", ":"), allow_nan=False)
    published = {"publication_status": "published", "version": "v0.0.0", "candidate_id": "fixture-web-example-only",
                 "published_at": "2026-10-17T00:00:00Z", "records": records,
                 "records_sha256": hashlib.sha256(canonical.encode("utf-8")).hexdigest()}
    samples = {"candidate.schema.json": candidate, "gap-export.schema.json": fixtures["gap-export.json"],
               "prebuild-source.schema.json": fixtures["prebuild-source.json"], "published-bundle.schema.json": published,
               "record.schema.json": records[0], "research-packet.schema.json": fixtures["research-packet.json"],
               "supplement-records.schema.json": fixtures["gap-records.json"], "tool-config.schema.json": fixtures["tool-config.json"]}
    paths = [ROOT / "ssr_knowledge" / "contracts.py", *sorted((ROOT / "contracts").glob("*.schema.json")),
             *(ROOT / "fixtures" / name for name in FIXTURES)]
    def git(*args):
        return subprocess.run(["git", "--no-optional-locks", *args], cwd=ROOT, check=True, capture_output=True,
                              text=True, encoding="utf-8").stdout.strip()
    return {"version": {"repo": "HGPT-StreamSuite/ssr-knowledge", "branch": git("branch", "--show-current"),
                        "base_commit": git("rev-parse", "HEAD"), "page_state": "uncommitted_local_page"},
            "schemas": schemas, "labels": LABELS, "samples": samples,
            "source_sha256": {path.relative_to(ROOT).as_posix(): hashlib.sha256(path.read_bytes()).hexdigest() for path in paths}}


def generated() -> str:
    return "/* Generated by tools/build_acceptance_web.py; synthetic fixtures only. */\n" + \
        "globalThis.KnowledgeAcceptanceData = " + json.dumps(bundle(), ensure_ascii=False, indent=2) + ";\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="read-only check; do not regenerate")
    args = parser.parse_args()
    expected = generated()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            print("FAIL: static schema bundle is stale or missing")
            return 1
        print("PASS: static bundle matches 8 contracts, 5 source fixtures and current HEAD/branch")
        return 0
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(expected, encoding="utf-8")
    print("Generated web/acceptance/dist/data.js (synthetic-only, no DB/network)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
